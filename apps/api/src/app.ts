import express from 'express';
import { prisma } from './db';
import { resolveTenant } from './middleware/tenantResolver';
import { errorHandler } from './middleware/errorHandler';
import auth from './modules/auth/routes/auth';
import users from './modules/auth/routes/user';
import author from './modules/auth/routes/author';
import { getJWKS } from './modules/auth/services/jwtService';
import { postRouter } from './modules/blog/routes/post';
import { categoryRouter } from './modules/blog/routes/category';
import { tagRouter } from './modules/blog/routes/tag';
import { bookmarkRouter } from './modules/blog/routes/bookmark';
import { likeRouter } from './modules/blog/routes/like';
import { draftRouter } from './modules/blog/routes/draft';
import { seoRouter } from './modules/blog/routes/seo';
import comments from './modules/comment/routes/comment';
import { pageRouter } from './modules/page/routes/page';
import { visitorRouter } from './modules/analytics/routes/visitor';
import { bugReportRouter } from './modules/analytics/routes/bugReport';
import { statsRouter } from './modules/analytics/routes/stats';
import { analyticsRouter } from './modules/analytics/routes/analytics';
import files from './modules/storage/routes/storage';
import metadata from './modules/storage/routes/metadata';
import images from './modules/storage/routes/images';
import backup from './modules/storage/routes/backup';
import upload from './modules/storage/routes/upload';
import { searchRouter } from './modules/blog/routes/search';

const app: express.Application = express();
app.disable('x-powered-by');
app.use(express.json({ limit: '10mb' }));
app.use(express.urlencoded({ extended: true, limit: '10mb' }));
app.get('/health', (_req, res) => { res.json({ status: 'ok', service: 'api' }); });
app.get('/ready', async (_req, res) => {
  try {
    await prisma.$queryRaw`SELECT 1`;
    res.json({ status: 'ready' });
  } catch { res.status(503).json({ status: 'unavailable' }); }
});
app.get('/.well-known/jwks.json', (_req, res) => { res.json(getJWKS()); });
app.use(resolveTenant);
app.use('/api/auth', auth);
app.use('/api/users', users);
app.use('/api/author', author);
app.use('/api/posts', postRouter);
app.use('/api/categories', categoryRouter);
app.use('/api/tags', tagRouter);
app.use('/api/bookmarks', bookmarkRouter);
app.use('/api/likes', likeRouter);
app.use('/api/drafts', draftRouter);
app.use('/api/comments', comments);
app.use('/api/pages', pageRouter);
app.use('/api/visitors', visitorRouter);
app.use('/api/bug-reports', bugReportRouter);
app.use('/api/stats', statsRouter);
app.use('/api/analytics', analyticsRouter);
app.use('/api/files', files);
app.use('/api/metadata', metadata);
app.use('/api/images', images);
app.use('/api/backup', backup);
app.use('/api/upload', upload);
app.use('/api/search', searchRouter);
app.use(seoRouter);
app.use((_req, res) => { res.status(404).json({ message: 'Route not found' }); });
app.use(errorHandler);
export default app;
